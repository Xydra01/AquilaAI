"""Generate a reproducible inventory of the Python reference implementation.

Usage (from the Aquila-cpp repo root):
    python docs/recon/tools/py_inventory.py            # writes docs/recon/PY_INVENTORY.md
    python docs/recon/tools/py_inventory.py --check    # verifies RECON_MAP.md covers every source file

The Python reference lives in a separate checkout of the Aquila-3.5 branch.
Its location comes from ``--py-ref`` or ``AQUILA_PY_REF`` and defaults to the
sibling directory ``../agent-projects``.

The file set is ``git ls-files --cached --others --exclude-standard`` so it
includes untracked-but-not-ignored work in that checkout.
"""
from __future__ import annotations

import argparse
import ast
import os
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parents[1]
INVENTORY = OUT_DIR / "PY_INVENTORY.md"
MAP = OUT_DIR / "RECON_MAP.md"
REPO = Path(
    os.environ.get("AQUILA_PY_REF") or OUT_DIR.parents[1].parent / "agent-projects"
).resolve()


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=REPO, capture_output=True, text=True, check=True
    ).stdout


def list_files() -> list[str]:
    files = git("ls-files", "--cached", "--others", "--exclude-standard").splitlines()
    return sorted(f for f in files if (REPO / f).is_file())


def git_states() -> dict[str, str]:
    states: dict[str, str] = {}
    for line in git("status", "--porcelain", "--untracked-files=all").splitlines():
        code, path = line[:2], line[3:].strip().strip('"')
        states[path] = "untracked" if code == "??" else f"modified({code.strip()})"
    return states


def package_of(rel: str) -> str:
    parts = rel.split("/")
    if parts[0] == "agent" and len(parts) > 2:
        return f"agent/{parts[1]}"
    return parts[0] if len(parts) > 1 else "(root)"


def resolve_import(rel: str, node: ast.ImportFrom) -> str | None:
    if node.level == 0:
        return node.module
    pkg = rel[:-3].split("/")[:-1] if not rel.endswith("__init__.py") else rel.split("/")[:-1]
    base = pkg[: len(pkg) - (node.level - 1)] if node.level > 1 else pkg
    return ".".join(base + ([node.module] if node.module else []))


def internal_targets(rel: str, tree: ast.AST) -> set[str]:
    targets: set[str] = set()
    for node in ast.walk(tree):
        mods: list[str] = []
        if isinstance(node, ast.Import):
            mods = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            m = resolve_import(rel, node)
            mods = [m] if m else []
        for m in mods:
            parts = m.split(".")
            if parts[0] == "agent" and len(parts) > 1:
                targets.add(f"agent/{parts[1]}")
            elif parts[0] in AGENT_SUBPKGS:
                targets.add(f"agent/{parts[0]}")
    return targets


AGENT_SUBPKGS = {"core", "gui", "storage", "parser", "policies", "research", "coding", "tool_library",
                 "capabilities", "functions", "remote", "aquila_runtime", "vision", "tasks"}


def analyze(rel: str) -> dict:
    src = (REPO / rel).read_text(encoding="utf-8", errors="replace")
    info = {"loc": src.count("\n") + (0 if src.endswith("\n") or not src else 1),
            "classes": [], "functions": [], "imports": set(), "error": None}
    try:
        tree = ast.parse(src)
    except SyntaxError as exc:
        info["error"] = f"SyntaxError: {exc}"
        return info
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            info["classes"].append(f"{node.name}:{node.lineno}")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            info["functions"].append(f"{node.name}:{node.lineno}")
    info["imports"] = internal_targets(rel, tree) - {package_of(rel)}
    return info


def source_files(files: list[str]) -> list[str]:
    return [f for f in files if f.endswith(".py")]


def write_inventory() -> None:
    files = list_files()
    states = git_states()
    py = source_files(files)
    rows = {f: analyze(f) for f in py}
    head = git("rev-parse", "--short", "HEAD").strip()
    branch = git("rev-parse", "--abbrev-ref", "HEAD").strip()

    by_pkg: dict[str, list[str]] = defaultdict(list)
    for f in py:
        by_pkg[package_of(f)].append(f)

    lines = [
        "# Python reference inventory (generated)",
        "",
        f"Generated by `docs/recon/tools/py_inventory.py` from the Python reference at "
        f"`{branch}@{head}` (plus any uncommitted work in that checkout). "
        "Do not edit by hand; rerun the script.",
        "",
        f"- Files considered (tracked + untracked, not ignored): **{len(files)}**",
        f"- Python files: **{len(py)}**, total LOC **{sum(r['loc'] for r in rows.values())}**",
        f"- Untracked Python files: **{sum(1 for f in py if states.get(f) == 'untracked')}**; "
        f"modified: **{sum(1 for f in py if states.get(f, '').startswith('modified'))}**",
        "",
        "## Packages",
        "",
        "| Package | Files | LOC | Depends on (internal imports) |",
        "|---|---:|---:|---|",
    ]
    for pkg in sorted(by_pkg, key=lambda p: -sum(rows[f]["loc"] for f in by_pkg[p])):
        deps = sorted(set().union(*(rows[f]["imports"] for f in by_pkg[pkg])))
        loc = sum(rows[f]["loc"] for f in by_pkg[pkg])
        lines.append(f"| `{pkg}` | {len(by_pkg[pkg])} | {loc} | {', '.join(deps) or '-'} |")

    lines += ["", "## Files", ""]
    for pkg in sorted(by_pkg):
        if pkg == "agent/tests":
            continue
        lines += [f"### `{pkg}`", "", "| File | State | LOC | Classes | Top-level functions |",
                  "|---|---|---:|---|---|"]
        for f in by_pkg[pkg]:
            r = rows[f]
            cls = ", ".join(r["classes"]) or "-"
            fns = ", ".join(r["functions"]) or "-"
            if r["error"]:
                fns = r["error"]
            lines.append(f"| `{f}` | {states.get(f, 'clean')} | {r['loc']} | {cls} | {fns} |")
        lines.append("")

    tests = by_pkg.get("agent/tests", [])
    lines += ["## Tests", "",
              f"`agent/tests/`: {len(tests)} files, {sum(rows[f]['loc'] for f in tests)} LOC "
              f"({sum(1 for f in tests if states.get(f) == 'untracked')} untracked). "
              "Listed by name only:", ""]
    lines += [f"- `{f}` ({states.get(f, 'clean')})" for f in tests]

    non_py = [f for f in files if not f.endswith(".py")]
    lines += ["", "## Non-Python files", ""]
    lines += [f"- `{f}` ({states.get(f, 'clean')})" for f in non_py]

    INVENTORY.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {INVENTORY.relative_to(OUT_DIR.parents[1])} from {REPO} @ {head}: "
          f"{len(py)} py files, {len(non_py)} other files")


def check_map() -> int:
    """Every non-test Python source file must be named in RECON_MAP.md (or its directory)."""
    text = MAP.read_text(encoding="utf-8")
    py = [f for f in source_files(list_files()) if not f.startswith("agent/tests/")]
    missing = []
    for f in py:
        if f in text:
            continue
        parent = f.rsplit("/", 1)[0] + "/"
        if f"`{parent}` (all files)" in text:
            continue
        missing.append(f)
    print(f"non-test python files: {len(py)}; covered: {len(py) - len(missing)}; missing: {len(missing)}")
    for f in missing:
        print(f"  MISSING {f}")
    return 1 if missing else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--py-ref", help="path to the Aquila-3.5 Python checkout")
    args = ap.parse_args()
    if args.py_ref:
        REPO = Path(args.py_ref).resolve()
    if not (REPO / "agent").is_dir():
        sys.exit(f"Python reference not found at {REPO} (set --py-ref or AQUILA_PY_REF)")
    sys.exit(check_map() if args.check else (write_inventory() or 0))
